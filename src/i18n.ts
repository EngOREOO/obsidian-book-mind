export const dir = (): "rtl" | "ltr" => (current === "ar" ? "rtl" : "ltr");

export function t(key: I18nKey, vars?: Record<string, string | number>): string {
  let s = DICT[current][key] ?? en[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.split("{" + k + "}").join(String(vars[k]));
  return s;
}

export const tk = (key: string): string => (key in en ? t(key as I18nKey) : key);

export const isArabic = (s: string): boolean => /[؀-ۿ]/.test(s);

export function niceDate(key: string): string {
  return new Date(key + "T00:00:00").toLocaleDateString(current === "ar" ? "ar-EG" : "en-US", { weekday: "short", day: "numeric", month: "short" });
}

export function periodLabel(period: string): string {
  if (period.length === 4) return period;
  return new Date(period + "-01T00:00:00").toLocaleDateString(current === "ar" ? "ar-EG" : "en-US", { month: "long", year: "numeric" });
}

